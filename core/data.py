"""Data loading.

Two sources, picked automatically:
- Google Sheets (when GSHEET_ID is set in .streamlit/secrets.toml): the same
  sheet the n8n workflow reads from and writes its AI reports to, so every
  n8n run shows up here.
- Local files in /data (fallback, for offline demos).
"""
from __future__ import annotations

import json
from pathlib import Path
from urllib.parse import quote

import pandas as pd

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
SALES_FILE = DATA_DIR / "lumora_daily_sales_2026.csv"
AI_REPORT_FILE = DATA_DIR / "ai_weekly_report.json"

SALES_TAB = "daily_sales"
REPORTS_TAB = "ai_reports"

SALES_COLUMNS = {
    "date", "channel", "sessions", "orders", "revenue_usd",
    "ad_spend_usd", "returns", "new_customers",
}


class DataError(Exception):
    """Raised when a data source is missing or malformed."""


# ---------- Google Sheets ----------

def sheet_csv_url(sheet_id: str, tab: str) -> str:
    """CSV export of one tab. The sheet must be shared as 'Anyone with the link can view'."""
    return f"https://docs.google.com/spreadsheets/d/{sheet_id}/gviz/tq?tqx=out:csv&sheet={quote(tab)}"


def _read_sheet(sheet_id: str, tab: str) -> pd.DataFrame:
    try:
        return pd.read_csv(sheet_csv_url(sheet_id, tab))
    except Exception as e:  # network, permissions, missing tab
        raise DataError(f"Could not read the '{tab}' tab from Google Sheets. "
                        "Check the sheet ID and that it is shared as 'Anyone with the link can view'.") from e


# ---------- sales ----------

def _clean_sales(df: pd.DataFrame) -> pd.DataFrame:
    df.columns = [str(c).strip() for c in df.columns]
    missing = SALES_COLUMNS - set(df.columns)
    if missing:
        raise DataError(f"Sales data is missing columns: {', '.join(sorted(missing))}")
    df = df.dropna(subset=["date", "channel"]).copy()
    df["date"] = pd.to_datetime(df["date"]).dt.normalize()
    num_cols = ["sessions", "orders", "revenue_usd", "ad_spend_usd", "returns", "new_customers"]
    df[num_cols] = df[num_cols].apply(pd.to_numeric, errors="coerce").fillna(0)
    return df.sort_values(["date", "channel"]).reset_index(drop=True)


def load_sales(sheet_id: str | None = None, path: Path = SALES_FILE) -> pd.DataFrame:
    if sheet_id:
        return _clean_sales(_read_sheet(sheet_id, SALES_TAB))
    if not path.exists():
        raise DataError(f"Sales file not found: {path.name}")
    return _clean_sales(pd.read_csv(path))


# ---------- AI report ----------

def _report_from_rows(rows: list[dict], week_start: str, week_end: str, meta: dict) -> dict:
    by_section: dict[str, list[str]] = {"summary": [], "highlight": [], "risk": [], "action": []}
    for row in rows:
        by_section.setdefault(str(row.get("section", "")).strip(), []).append(str(row.get("text", "")))
    return {
        "summary": " ".join(by_section["summary"]),
        "highlights": by_section["highlight"],
        "risks": by_section["risk"],
        "actions": by_section["action"],
        "meta": meta,
        "week_start": week_start,
        "week_end": week_end,
    }


def load_ai_report(sheet_id: str | None = None, path: Path = AI_REPORT_FILE) -> dict | None:
    """Latest AI report. From Sheets: the newest run in the ai_reports tab written by n8n."""
    if sheet_id:
        df = _read_sheet(sheet_id, REPORTS_TAB)
        if df.empty or "generated_at" not in df.columns:
            return None
        latest = df["generated_at"].astype(str).max()
        run = df[df["generated_at"].astype(str) == latest]
        return _report_from_rows(
            run.to_dict("records"),
            str(run["week_start"].iloc[0])[:10], str(run["week_end"].iloc[0])[:10],
            {"Generated by": "n8n workflow 'AI Weekly Sales Report'", "Generated at": latest},
        )
    if not path.exists():
        return None
    raw = json.loads(path.read_text(encoding="utf-8"))
    meta = {m.get("label"): m.get("value") for m in raw.get("meta", [])}
    report = _report_from_rows(raw.get("rows", []), raw.get("week_start", ""), raw.get("week_end", ""), meta)
    # The bundled file is example output; a report saved by "Generate with AI" is a live one.
    report["sample"] = "dashboard" not in str(meta.get("Generated by", "")).lower()
    return report


def save_ai_report(report: dict, week_start: str, week_end: str, path: Path = AI_REPORT_FILE,
                   provider_label: str = "AI") -> None:
    """Save a report generated from the dashboard (local mode)."""
    rows = [{"section": "summary", "text": report["summary"]}]
    for key, section in (("highlights", "highlight"), ("risks", "risk"), ("actions", "action")):
        rows += [{"section": section, "text": t} for t in report.get(key, [])]
    payload = {
        "week_start": week_start,
        "week_end": week_end,
        "rows": rows,
        "meta": [
            {"label": "Report week", "value": f"{week_start} to {week_end}"},
            {"label": "Generated by", "value": f"Lumora dashboard ({provider_label} API)"},
        ],
    }
    path.write_text(json.dumps(payload, indent=1, ensure_ascii=False), encoding="utf-8")
